    def save_result_metadata(self) -> None:
        try:
            for row in self.summary:
                key = model_row_name(row)
                if not self.model_name_vars[key].get().strip():
                    raise ValueError("Evaluation names cannot be empty")
            for row in self.summary:
                key = model_row_name(row)
                if row.get("result_file"):
                    update_metadata(row["result_file"], self.model_name_vars[key].get(), self.note_vars[key].get())
            self.load_results()
            self.status.set("Saved evaluation names and notes.")
        except Exception as exc:
            self.messagebox.showerror("Save failed", str(exc))

    def model_name_map(self) -> Dict[str, str]:
        names = [var.get().strip() or original for original, var in self.model_name_vars.items()]
        return {
            original: (var.get().strip() if names.count(var.get().strip()) == 1 else original)
            for original, var in self.model_name_vars.items()
            if var.get().strip() and var.get().strip() != original
        }

    def selected_models(self) -> List[str]:
        return [
            original
            for original, var in self.model_enabled_vars.items()
            if bool(var.get())
        ]

    def set_all_models_enabled(self, enabled: bool) -> None:
        for var in self.model_enabled_vars.values():
            var.set(bool(enabled))
        self.status.set("Selected all models." if enabled else "Unselected all models.")

    def remove_selected_models(self) -> None:
        selected = set(self.selected_models())
        if not selected:
            self.status.set("No models selected for removal.")
            return
        remaining = {
            name: (var.get(), self.note_vars[name].get(), self.model_enabled_vars[name].get())
            for name, var in self.model_name_vars.items() if name not in selected
        }
        self.summary = [row for row in self.summary if model_row_name(row) not in selected]
        self.episodes = [row for row in self.episodes if model_row_name(row) not in selected]
        self._build_model_entries()
        for name, (display_name, note, enabled) in remaining.items():
            self.model_name_vars[name].set(display_name)
            self.note_vars[name].set(note)
            self.model_enabled_vars[name].set(enabled)
        self.status.set("Removed {} evaluations from the list. Saved files are unchanged.".format(len(selected)))

    def titles(self) -> Dict[str, str]:
        return {
            key: var.get().strip()
            for key, var in self.title_vars.items()
            if var.get().strip()
        }

    def reset_titles(self) -> None:
        for key, value in DEFAULT_TITLES.items():
            self.title_vars[key].set(value)
        self.status.set("Titles reset.")

    def _prepared_rows(self) -> Tuple[List[Dict[str, Any]], List[Dict[str, Any]]]:
        if not self.results_loaded:
            self.load_results()
        summary, episodes = filter_model_rows(
            copy.deepcopy(self.summary),
            copy.deepcopy(self.episodes),
            self.selected_models(),
        )
        summary, episodes = apply_model_name_map(
            summary,
            episodes,
            self.model_name_map(),
        )
        return sort_summary_by_model_name(summary), episodes

