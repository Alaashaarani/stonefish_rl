"""Plot and export evaluation results."""

if __package__ in (None, ""):
    import _bootstrap  # Enable direct execution from any working directory.

import argparse
from library.evaluation_plots import launch_gui, plot_evaluation_results

def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Plot evaluation results generated by stonefish_rl_evaluation.py"
    )
    parser.add_argument(
        "eval_output_path",
        nargs="?",
        type=str,
        default=None,
        help="Evaluation directory, single result file, or quoted glob such as 'evaluation_results/PPO_h2*'",
    )
    parser.add_argument(
        "--output-dir",
        type=str,
        default=None,
        help="Directory where plots should be saved. Default: <eval_output_path>/plots",
    )
    parser.add_argument(
        "--dpi",
        type=int,
        default=300,
        help="Figure DPI. Default: 300",
    )
    parser.add_argument(
        "--show",
        action="store_true",
        help="Show figures interactively in addition to saving them.",
    )
    parser.add_argument(
        "--gui",
        action="store_true",
        help="Open a small GUI to edit model names/titles, preview figures, and save plots.",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    if args.gui:
        launch_gui(args.eval_output_path)
        return

    if not args.eval_output_path:
        raise SystemExit("eval_output_path is required unless --gui is used.")

    plot_evaluation_results(
        eval_output_path=args.eval_output_path,
        output_dir=args.output_dir,
        dpi=args.dpi,
        show=args.show,
    )


if __name__ == "__main__":
    main()
