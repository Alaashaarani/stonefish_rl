def save_current_figure(path: Path, dpi: int, show: bool) -> None:
    plt.tight_layout()
    plt.savefig(str(path), dpi=dpi, bbox_inches="tight")
    if show:
        plt.show()
    plt.close()


def model_labels(summary: List[Dict[str, Any]]) -> List[str]:
    labels = []
    for idx, row in enumerate(summary):
        name = str(row.get("model_name", "model_{}".format(idx)))
        alg = str(row.get("algorithm", ""))
        if alg:
            label = "{}\n{}".format(name, alg)
        else:
            label = name
        labels.append(label)
    return labels


def get_summary_value(row: Dict[str, Any], keys: List[str]) -> float:
    for key in keys:
        if key in row:
            return _safe_float(row[key])
    return float("nan")


def get_title(titles: Optional[Dict[str, str]], key: str) -> str:
    """Return title override if supplied, otherwise the default title."""
    if titles and titles.get(key):
        return str(titles[key])
    return DEFAULT_TITLES.get(key, key)


def apply_model_name_map(
    summary: List[Dict[str, Any]],
    episodes: List[Dict[str, Any]],
    model_name_map: Optional[Dict[str, str]],
) -> Tuple[List[Dict[str, Any]], List[Dict[str, Any]]]:
    """Return copies of rows with model_name replaced by display names."""
    if not model_name_map:
        return summary, episodes

    def rename_rows(rows: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
        renamed = []
        for row in rows:
            new_row = dict(row)
            original = str(new_row.get("model_name", new_row.get("model_id", "model")))
            if original in model_name_map and model_name_map[original]:
                new_row["model_name"] = model_name_map[original]
            renamed.append(new_row)
        return renamed

    return rename_rows(summary), rename_rows(episodes)




def get_collision_summary(row: Dict[str, Any]) -> Tuple[float, float, float]:
    """Return mean/std/total of per-episode collision-reward sums.

    The preferred fields are collision_reward_sum_mean,
    collision_reward_sum_std, and collision_reward_sum_total. Older mean-based
    fields are kept only as fallback for backward compatibility.
    """
    mean_value = get_summary_value(row, [
        "collision_reward_sum_mean",
        "mean_collision_reward_mean",
        "collision_reward_mean",
        "mean_collision_reward",
        "final_collision_reward_mean",
    ])
    std_value = get_summary_value(row, [
        "collision_reward_sum_std",
        "mean_collision_reward_std",
        "collision_reward_std",
        "std_collision_reward",
        "final_collision_reward_std",
    ])
    total_value = get_summary_value(row, [
        "collision_reward_sum_total",
    ])
    return mean_value, std_value, total_value


def subplot_grid_for_models(num_models: int) -> Tuple[int, int]:
    """Return rows/columns for one subplot per model."""
    cols = 1 if num_models <= 6 else 2
    rows = int(math.ceil(num_models / cols))
    return rows, cols


def plot_metric_per_model(
    grouped: List[Tuple[str, List[Dict[str, Any]]]],
    *,
    value_getter,
    ylabel: str,
    title: str,
    output_path: Path,
    dpi: int,
    show: bool,
    yticks: Optional[Tuple[List[float], List[str]]] = None,
) -> None:
    """Plot one episode curve subplot per model."""
    if not grouped:
        return

    rows, cols = subplot_grid_for_models(len(grouped))
    fig_width = 8 if cols == 1 else 14
    fig_height = max(3.0 * rows, 4.5)
    fig, axes = plt.subplots(rows, cols, figsize=(fig_width, fig_height), squeeze=False)
    axes_flat = axes.flatten()

    for ax, (model_name, model_rows) in zip(axes_flat, grouped):
        rows_sorted = sorted(model_rows, key=lambda r: _safe_int(r.get("episode")))
        ep = np.array([_safe_int(r.get("episode")) for r in rows_sorted], dtype=int)
        values = np.array([value_getter(r) for r in rows_sorted], dtype=float)

        ax.plot(ep, values, marker="o", linewidth=1.8)
        ax.set_title(model_name, fontsize=10)
        ax.set_xlabel("Episode")
        ax.set_ylabel(ylabel)
        ax.grid(True, linestyle="--", alpha=0.5)
        if yticks is not None:
            ax.set_yticks(yticks[0], yticks[1])
            ax.set_ylim(-0.1, 1.1)

    for ax in axes_flat[len(grouped):]:
        ax.axis("off")

    fig.suptitle(title, fontsize=14)
    save_current_figure(output_path, dpi, show)


def plot_summary_bars(
    summary: List[Dict[str, Any]],
    output_dir: Path,
    dpi: int,
    show: bool,
    titles: Optional[Dict[str, str]] = None,
) -> None:
    """Create core comparison bar plots."""
    if not summary:
        return

    labels = model_labels(summary)
    x = np.arange(len(labels))

    success_rate = np.array([get_summary_value(r, ["success_rate"]) for r in summary], dtype=float)
    mean_reward = np.array([get_summary_value(r, ["mean_reward"]) for r in summary], dtype=float)
    std_reward = np.array([get_summary_value(r, ["std_reward"]) for r in summary], dtype=float)
    mean_steps = np.array([get_summary_value(r, ["mean_steps"]) for r in summary], dtype=float)
    std_steps = np.array([get_summary_value(r, ["std_steps"]) for r in summary], dtype=float)
    collision_pairs = [get_collision_summary(r) for r in summary]
    mean_collision_sum = np.array([p[0] for p in collision_pairs], dtype=float)
    std_collision_sum = np.array([p[1] for p in collision_pairs], dtype=float)

    # Some summary writers store success_rate as percent rather than fraction.
    if np.nanmax(success_rate) <= 1.0:
        success_rate_plot = success_rate * 100.0
    else:
        success_rate_plot = success_rate

    # Success rate
    plt.figure(figsize=(max(8, len(labels) * 1.6), 5))
    plt.bar(x, success_rate_plot)
    plt.xticks(x, labels, rotation=25, ha="right")
    plt.ylabel("Success rate (%)")
    plt.title(get_title(titles, "01_success_rate"))
    plt.ylim(0, 105)
    plt.grid(axis="y", linestyle="--", alpha=0.5)
    for i, value in enumerate(success_rate_plot):
        if not math.isnan(value):
            plt.text(i, value + 2, "{:.1f}%".format(value), ha="center", va="bottom")
    save_current_figure(output_dir / "01_success_rate.png", dpi, show)

    # Mean reward with std
    plt.figure(figsize=(max(8, len(labels) * 1.6), 5))
    plt.bar(x, mean_reward, yerr=std_reward, capsize=5)
    plt.xticks(x, labels, rotation=25, ha="right")
    plt.ylabel("Total reward per episode")
    plt.title(get_title(titles, "02_mean_reward"))
    plt.grid(axis="y", linestyle="--", alpha=0.5)
    save_current_figure(output_dir / "02_mean_reward.png", dpi, show)

    # Mean steps with std
    plt.figure(figsize=(max(8, len(labels) * 1.6), 5))
    plt.bar(x, mean_steps, yerr=std_steps, capsize=5)
    plt.xticks(x, labels, rotation=25, ha="right")
    plt.ylabel("Steps per episode")
    plt.title(get_title(titles, "03_mean_steps"))
    plt.grid(axis="y", linestyle="--", alpha=0.5)
    save_current_figure(output_dir / "03_mean_steps.png", dpi, show)

    # Mean per-episode collision-reward sum with std, if available
    if np.any(np.isfinite(mean_collision_sum)):
        yerr = std_collision_sum.copy()
        yerr[~np.isfinite(yerr)] = 0.0
        plt.figure(figsize=(max(8, len(labels) * 1.6), 5))
        plt.bar(x, mean_collision_sum, yerr=yerr, capsize=5)
        plt.xticks(x, labels, rotation=25, ha="right")
        plt.ylabel("Collision reward sum per episode")
        plt.title(get_title(titles, "04_collision_reward_sum"))
        plt.grid(axis="y", linestyle="--", alpha=0.5)
        save_current_figure(output_dir / "04_collision_reward_sum.png", dpi, show)


def plot_episode_curves(
    episodes: List[Dict[str, Any]],
    output_dir: Path,
    dpi: int,
    show: bool,
    titles: Optional[Dict[str, str]] = None,
) -> None:
    """Plot per-episode reward, steps, and success markers."""
    grouped = group_by_model(episodes)
    if not grouped:
        return

    plot_metric_per_model(
        grouped,
        value_getter=lambda row: _safe_float(row.get("total_reward")),
        ylabel="Total reward",
        title=get_title(titles, "05_reward_per_episode"),
        output_path=output_dir / "05_reward_per_episode.png",
        dpi=dpi,
        show=show,
    )

    plot_metric_per_model(
        grouped,
        value_getter=lambda row: _safe_float(row.get("steps")),
        ylabel="Steps",
        title=get_title(titles, "06_steps_per_episode"),
        output_path=output_dir / "06_steps_per_episode.png",
        dpi=dpi,
        show=show,
    )

    plot_metric_per_model(
        grouped,
        value_getter=lambda row: 1.0 if _safe_bool(row.get("success")) else 0.0,
        ylabel="Success",
        title=get_title(titles, "07_success_per_episode"),
        output_path=output_dir / "07_success_per_episode.png",
        dpi=dpi,
        show=show,
        yticks=([0, 1], ["Fail/Timeout", "Success"]),
    )


def plot_boxplots(
    episodes: List[Dict[str, Any]],
    output_dir: Path,
    dpi: int,
    show: bool,
    titles: Optional[Dict[str, str]] = None,
) -> None:
    """Plot reward and step distributions as boxplots."""
    grouped = group_by_model(episodes)
    if not grouped:
        return

    labels = [g[0] for g in grouped]
    reward_data = []
    steps_data = []

    for _, rows in grouped:
        reward_values = [_safe_float(r.get("total_reward")) for r in rows]
        step_values = [_safe_float(r.get("steps")) for r in rows]
        reward_data.append([v for v in reward_values if not math.isnan(v)])
        steps_data.append([v for v in step_values if not math.isnan(v)])

    if any(len(v) > 0 for v in reward_data):
        plt.figure(figsize=(max(8, len(labels) * 1.5), 5))
        plt.boxplot(reward_data, labels=labels, showmeans=True)
        plt.xticks(rotation=25, ha="right")
        plt.ylabel("Total reward")
        plt.title(get_title(titles, "08_reward_boxplot"))
        plt.grid(axis="y", linestyle="--", alpha=0.5)
        save_current_figure(output_dir / "08_reward_boxplot.png", dpi, show)

    if any(len(v) > 0 for v in steps_data):
        plt.figure(figsize=(max(8, len(labels) * 1.5), 5))
        plt.boxplot(steps_data, labels=labels, showmeans=True)
        plt.xticks(rotation=25, ha="right")
        plt.ylabel("Steps")
        plt.title(get_title(titles, "09_steps_boxplot"))
        plt.grid(axis="y", linestyle="--", alpha=0.5)
        save_current_figure(output_dir / "09_steps_boxplot.png", dpi, show)



def plot_collision_reward_boxplot(
    episodes: List[Dict[str, Any]],
    output_dir: Path,
    dpi: int,
    show: bool,
    titles: Optional[Dict[str, str]] = None,
) -> None:
    """Plot distribution of per-episode collision-reward sums if available."""
    grouped = group_by_model(episodes)
    if not grouped:
        return

    labels = []
    data = []
    for model_name, rows in grouped:
        values = []
        for row in rows:
            value = _safe_float(row.get("collision_reward_sum", row.get("mean_collision_reward", row.get("collision_reward"))))
            if not math.isnan(value):
                values.append(value)
        if values:
            labels.append(model_name)
            data.append(values)

    if not data:
        return

    plt.figure(figsize=(max(8, len(labels) * 1.5), 5))
    plt.boxplot(data, labels=labels, showmeans=True)
    plt.xticks(rotation=25, ha="right")
    plt.ylabel("Collision reward sum per episode")
    plt.title(get_title(titles, "10_collision_reward_sum_boxplot"))
    plt.grid(axis="y", linestyle="--", alpha=0.5)
    save_current_figure(output_dir / "10_collision_reward_sum_boxplot.png", dpi, show)


def plot_final_errors(
    episodes: List[Dict[str, Any]],
    output_dir: Path,
    dpi: int,
    show: bool,
    titles: Optional[Dict[str, str]] = None,
) -> None:
    """Plot final error metrics if present in the episode CSV."""
    grouped = group_by_model(episodes)
    if not grouped:
        return

    candidate_keys = [
        ("final_xy_error", "Final xy error"),
        ("final_z_error", "Final z error"),
        ("final_yaw_error", "Final yaw error"),
        ("final_distance_error", "Final distance error"),
    ]

    for key, title in candidate_keys:
        available = any(key in r and not math.isnan(_safe_float(r.get(key))) for r in episodes)
        if not available:
            continue

        labels = []
        data = []
        for model_name, rows in grouped:
            values = [_safe_float(r.get(key)) for r in rows]
            values = [v for v in values if not math.isnan(v)]
            if values:
                labels.append(model_name)
                data.append(values)

        if not data:
            continue

        plt.figure(figsize=(max(8, len(labels) * 1.5), 5))
        plt.boxplot(data, labels=labels, showmeans=True)
        plt.xticks(rotation=25, ha="right")
        plt.ylabel(key)
        title_key = "10_{}_boxplot".format(key)
        plt.title(get_title(titles, title_key))
        plt.grid(axis="y", linestyle="--", alpha=0.5)
        save_current_figure(output_dir / "10_{}_boxplot.png".format(key), dpi, show)


def plot_summary_table(
    summary: List[Dict[str, Any]],
    output_dir: Path,
    dpi: int,
    show: bool,
    titles: Optional[Dict[str, str]] = None,
) -> None:
    """Render a compact summary table as an image."""
    if not summary:
        return

    display_cols = [
        "Model", "Alg", "Success", "Mean Reward", "Std Reward",
        "Mean Steps", "Std Steps", "Collision Sum Mean", "Collision Sum Std", "Collision Sum Total"
    ]

    rows = []
    for row in summary:
        success = get_summary_value(row, ["success_rate"])
        if not math.isnan(success) and success <= 1.0:
            success = 100.0 * success
        rows.append([
            str(row.get("model_name", "")),
            str(row.get("algorithm", "")),
            "{:.1f}%".format(success) if not math.isnan(success) else "",
            "{:.2f}".format(get_summary_value(row, ["mean_reward"])) if not math.isnan(get_summary_value(row, ["mean_reward"])) else "",
            "{:.2f}".format(get_summary_value(row, ["std_reward"])) if not math.isnan(get_summary_value(row, ["std_reward"])) else "",
            "{:.1f}".format(get_summary_value(row, ["mean_steps"])) if not math.isnan(get_summary_value(row, ["mean_steps"])) else "",
            "{:.1f}".format(get_summary_value(row, ["std_steps"])) if not math.isnan(get_summary_value(row, ["std_steps"])) else "",
            "{:.3f}".format(get_collision_summary(row)[0]) if not math.isnan(get_collision_summary(row)[0]) else "",
            "{:.3f}".format(get_collision_summary(row)[1]) if not math.isnan(get_collision_summary(row)[1]) else "",
            "{:.3f}".format(get_collision_summary(row)[2]) if not math.isnan(get_collision_summary(row)[2]) else "",
        ])

    fig_width = max(10, len(display_cols) * 1.5)
    fig_height = max(2.5, 0.5 + 0.45 * len(rows))
    fig, ax = plt.subplots(figsize=(fig_width, fig_height))
    ax.axis("off")
    table = ax.table(cellText=rows, colLabels=display_cols, loc="center", cellLoc="center")
    table.auto_set_font_size(False)
    table.set_fontsize(9)
    table.scale(1.0, 1.3)
    ax.set_title(get_title(titles, "00_summary_table"), pad=15)
    save_current_figure(output_dir / "00_summary_table.png", dpi, show)


