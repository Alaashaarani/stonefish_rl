def plot_evaluation_results(
    eval_output_path: str,
    output_dir: Optional[str] = None,
    dpi: int = 300,
    show: bool = False,
    model_name_map: Optional[Dict[str, str]] = None,
    titles: Optional[Dict[str, str]] = None,
) -> Path:
    """
    Plot comparison results generated by evaluate_docking_compare.py.

    Parameters
    ----------
    eval_output_path : str
        Path to the evaluation output directory.
    output_dir : Optional[str]
        Directory where plots should be saved. If None, creates <eval_output_path>/plots.
    dpi : int
        Figure DPI.
    show : bool
        If True, show figures interactively.

    Returns
    -------
    Path
        Path to the generated plot directory.
    """
    eval_dir = Path(eval_output_path).expanduser().resolve()
    if not eval_dir.exists():
        raise FileNotFoundError("Evaluation output path does not exist: {}".format(eval_dir))
    if not eval_dir.is_dir():
        raise NotADirectoryError("Evaluation output path must be a directory: {}".format(eval_dir))

    if output_dir is None:
        plot_dir = eval_dir / "plots"
    else:
        plot_dir = Path(output_dir).expanduser().resolve()
    ensure_dir(plot_dir)

    summary = load_summary(eval_dir)
    episodes = load_episodes(eval_dir)
    summary, episodes = apply_model_name_map(summary, episodes, model_name_map)

    print("Loaded {} summary rows".format(len(summary)))
    print("Loaded {} episode rows".format(len(episodes)))
    print("Saving plots to: {}".format(plot_dir))
    print("Matplotlib version: {}".format(matplotlib.__version__))

    plot_summary_table(summary, plot_dir, dpi, show, titles)
    plot_summary_bars(summary, plot_dir, dpi, show, titles)
    plot_episode_curves(episodes, plot_dir, dpi, show, titles)
    plot_boxplots(episodes, plot_dir, dpi, show, titles)
    plot_collision_reward_boxplot(episodes, plot_dir, dpi, show, titles)
    plot_final_errors(episodes, plot_dir, dpi, show, titles)

    print("Done. Generated plots:")
    for path in sorted(plot_dir.glob("*.png")):
        print("  - {}".format(path.name))

    return plot_dir


class PlotEvaluationGui:
    """Small tkinter GUI for previewing and saving evaluation plots."""

    def __init__(self):
        import tkinter as tk
        from tkinter import filedialog, messagebox, ttk

        self.tk = tk
        self.filedialog = filedialog
        self.messagebox = messagebox
        self.ttk = ttk

        self.root = tk.Tk()
        self.root.title("Stonefish RL Evaluation Plotter")
        self.root.geometry("1180x780")

        self.eval_dir = tk.StringVar(value="evaluation_results")
        self.output_dir = tk.StringVar(value="")
        self.dpi = tk.IntVar(value=300)
        self.status = tk.StringVar(value="Load an evaluation directory to begin.")

        self.summary = []
        self.episodes = []
        self.model_name_vars = {}
        self.title_vars = {
            key: tk.StringVar(value=value)
            for key, value in DEFAULT_TITLES.items()
        }

        self._build_layout()

    def run(self) -> None:
        self.root.mainloop()

    def _build_layout(self) -> None:
        root = self.ttk.Frame(self.root, padding=8)
        root.pack(fill=self.tk.BOTH, expand=True)

        top = self.ttk.LabelFrame(root, text="Input / Output", padding=8)
        top.pack(fill=self.tk.X)

        self.ttk.Label(top, text="Evaluation dir").grid(row=0, column=0, sticky=self.tk.W)
        self.ttk.Entry(top, textvariable=self.eval_dir, width=80).grid(row=0, column=1, sticky=self.tk.EW)
        self.ttk.Button(top, text="Browse", command=self._browse_eval_dir).grid(row=0, column=2)
        self.ttk.Button(top, text="Load", command=self.load_results).grid(row=0, column=3)

        self.ttk.Label(top, text="Output dir").grid(row=1, column=0, sticky=self.tk.W)
        self.ttk.Entry(top, textvariable=self.output_dir, width=80).grid(row=1, column=1, sticky=self.tk.EW)
        self.ttk.Button(top, text="Browse", command=self._browse_output_dir).grid(row=1, column=2)
        self.ttk.Label(top, text="DPI").grid(row=1, column=3, sticky=self.tk.E)
        self.ttk.Spinbox(top, from_=80, to=800, textvariable=self.dpi, width=6).grid(row=1, column=4)
        top.columnconfigure(1, weight=1)

        middle = self.ttk.PanedWindow(root, orient=self.tk.HORIZONTAL)
        middle.pack(fill=self.tk.BOTH, expand=True, pady=8)

        self.model_frame = self.ttk.LabelFrame(middle, text="Model Display Names", padding=8)
        self.title_frame = self.ttk.LabelFrame(middle, text="Figure Titles", padding=8)
        middle.add(self.model_frame, weight=1)
        middle.add(self.title_frame, weight=1)

        self._build_title_entries()

        bottom = self.ttk.Frame(root)
        bottom.pack(fill=self.tk.X)
        self.ttk.Button(bottom, text="Preview All", command=self.preview_all).pack(side=self.tk.LEFT)
        self.ttk.Button(bottom, text="Preview 05-07", command=self.preview_episode_plots).pack(side=self.tk.LEFT, padx=4)
        self.ttk.Button(bottom, text="Save Plots", command=self.save_plots).pack(side=self.tk.LEFT)
        self.ttk.Button(bottom, text="Reset Titles", command=self.reset_titles).pack(side=self.tk.LEFT, padx=4)
        self.ttk.Label(bottom, textvariable=self.status, anchor=self.tk.W).pack(side=self.tk.LEFT, fill=self.tk.X, expand=True, padx=12)

    def _build_title_entries(self) -> None:
        canvas = self.tk.Canvas(self.title_frame)
        scrollbar = self.ttk.Scrollbar(self.title_frame, orient=self.tk.VERTICAL, command=canvas.yview)
        content = self.ttk.Frame(canvas)
        content.bind("<Configure>", lambda event: canvas.configure(scrollregion=canvas.bbox("all")))
        canvas.create_window((0, 0), window=content, anchor=self.tk.NW)
        canvas.configure(yscrollcommand=scrollbar.set)

        canvas.pack(side=self.tk.LEFT, fill=self.tk.BOTH, expand=True)
        scrollbar.pack(side=self.tk.RIGHT, fill=self.tk.Y)

        for row_index, (key, var) in enumerate(self.title_vars.items()):
            self.ttk.Label(content, text=key, width=34).grid(row=row_index, column=0, sticky=self.tk.W, pady=2)
            self.ttk.Entry(content, textvariable=var, width=58).grid(row=row_index, column=1, sticky=self.tk.EW, pady=2)
        content.columnconfigure(1, weight=1)

    def _browse_eval_dir(self) -> None:
        path = self.filedialog.askdirectory(initialdir=str(Path.cwd()))
        if path:
            self.eval_dir.set(path)

    def _browse_output_dir(self) -> None:
        initial = self.output_dir.get() or self.eval_dir.get()
        path = self.filedialog.askdirectory(initialdir=initial)
        if path:
            self.output_dir.set(path)

    def load_results(self) -> None:
        try:
            eval_dir = Path(self.eval_dir.get()).expanduser().resolve()
            self.summary = load_summary(eval_dir)
            self.episodes = load_episodes(eval_dir)
            if not self.output_dir.get():
                self.output_dir.set(str(eval_dir / "plots"))
            self._build_model_entries()
            self.status.set(
                "Loaded {} models and {} episodes.".format(
                    len(group_by_model(self.episodes)),
                    len(self.episodes),
                )
            )
        except Exception as exc:
            self.messagebox.showerror("Load failed", str(exc))
            self.status.set("Load failed: {}".format(exc))

    def _build_model_entries(self) -> None:
        for child in self.model_frame.winfo_children():
            child.destroy()

        grouped = group_by_model(self.episodes)
        self.model_name_vars = {}

        canvas = self.tk.Canvas(self.model_frame)
        scrollbar = self.ttk.Scrollbar(self.model_frame, orient=self.tk.VERTICAL, command=canvas.yview)
        content = self.ttk.Frame(canvas)
        content.bind("<Configure>", lambda event: canvas.configure(scrollregion=canvas.bbox("all")))
        canvas.create_window((0, 0), window=content, anchor=self.tk.NW)
        canvas.configure(yscrollcommand=scrollbar.set)
        canvas.pack(side=self.tk.LEFT, fill=self.tk.BOTH, expand=True)
        scrollbar.pack(side=self.tk.RIGHT, fill=self.tk.Y)

        self.ttk.Label(content, text="Original", width=36).grid(row=0, column=0, sticky=self.tk.W)
        self.ttk.Label(content, text="Display name", width=44).grid(row=0, column=1, sticky=self.tk.W)

        for row_index, (model_name, _) in enumerate(grouped, start=1):
            var = self.tk.StringVar(value=model_name)
            self.model_name_vars[model_name] = var
            self.ttk.Label(content, text=model_name, width=36).grid(row=row_index, column=0, sticky=self.tk.W, pady=2)
            self.ttk.Entry(content, textvariable=var, width=44).grid(row=row_index, column=1, sticky=self.tk.EW, pady=2)
        content.columnconfigure(1, weight=1)

    def model_name_map(self) -> Dict[str, str]:
        return {
            original: var.get().strip()
            for original, var in self.model_name_vars.items()
            if var.get().strip() and var.get().strip() != original
        }

    def titles(self) -> Dict[str, str]:
        return {
            key: var.get().strip()
            for key, var in self.title_vars.items()
            if var.get().strip()
        }

    def reset_titles(self) -> None:
        for key, value in DEFAULT_TITLES.items():
            self.title_vars[key].set(value)
        self.status.set("Titles reset.")

    def _prepared_rows(self) -> Tuple[List[Dict[str, Any]], List[Dict[str, Any]]]:
        if not self.summary or not self.episodes:
            self.load_results()
        return apply_model_name_map(
            copy.deepcopy(self.summary),
            copy.deepcopy(self.episodes),
            self.model_name_map(),
        )

    def preview_episode_plots(self) -> None:
        try:
            summary, episodes = self._prepared_rows()
            with tempfile.TemporaryDirectory(prefix="stonefish_eval_preview_") as temp_dir:
                plot_episode_curves(episodes, Path(temp_dir), int(self.dpi.get()), True, self.titles())
            self.status.set("Previewed plots 05-07. Close plot windows to continue.")
        except Exception as exc:
            self.messagebox.showerror("Preview failed", str(exc))
            self.status.set("Preview failed: {}".format(exc))

    def preview_all(self) -> None:
        try:
            summary, episodes = self._prepared_rows()
            with tempfile.TemporaryDirectory(prefix="stonefish_eval_preview_") as temp_dir:
                temp_path = Path(temp_dir)
                plot_summary_table(summary, temp_path, int(self.dpi.get()), True, self.titles())
                plot_summary_bars(summary, temp_path, int(self.dpi.get()), True, self.titles())
                plot_episode_curves(episodes, temp_path, int(self.dpi.get()), True, self.titles())
                plot_boxplots(episodes, temp_path, int(self.dpi.get()), True, self.titles())
                plot_collision_reward_boxplot(episodes, temp_path, int(self.dpi.get()), True, self.titles())
                plot_final_errors(episodes, temp_path, int(self.dpi.get()), True, self.titles())
            self.status.set("Previewed all plots. Close plot windows to continue.")
        except Exception as exc:
            self.messagebox.showerror("Preview failed", str(exc))
            self.status.set("Preview failed: {}".format(exc))

    def save_plots(self) -> None:
        try:
            output_dir = self.output_dir.get().strip() or None
            plot_dir = plot_evaluation_results(
                self.eval_dir.get(),
                output_dir=output_dir,
                dpi=int(self.dpi.get()),
                show=False,
                model_name_map=self.model_name_map(),
                titles=self.titles(),
            )
            self.status.set("Saved plots to {}".format(plot_dir))
        except Exception as exc:
            self.messagebox.showerror("Save failed", str(exc))
            self.status.set("Save failed: {}".format(exc))


def launch_gui() -> None:
    PlotEvaluationGui().run()


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Plot evaluation results generated by evaluate_docking_compare.py"
    )
    parser.add_argument(
        "eval_output_path",
        nargs="?",
        type=str,
        default=None,
        help="Path to the evaluation output directory containing summary.csv and episodes_all_models.csv",
    )
    parser.add_argument(
        "--output-dir",
        type=str,
        default=None,
        help="Directory where plots should be saved. Default: <eval_output_path>/plots",
    )
    parser.add_argument(
        "--dpi",
        type=int,
        default=300,
        help="Figure DPI. Default: 300",
    )
    parser.add_argument(
        "--show",
        action="store_true",
        help="Show figures interactively in addition to saving them.",
    )
    parser.add_argument(
        "--gui",
        action="store_true",
        help="Open a small GUI to edit model names/titles, preview figures, and save plots.",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    if args.gui:
        launch_gui()
        return

    if not args.eval_output_path:
        raise SystemExit("eval_output_path is required unless --gui is used.")

    plot_evaluation_results(
        eval_output_path=args.eval_output_path,
        output_dir=args.output_dir,
        dpi=args.dpi,
        show=args.show,
    )


if __name__ == "__main__":
    main()
