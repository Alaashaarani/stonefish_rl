def _safe_float(value: Any, default: float = float("nan")) -> float:
    """Convert value to float safely."""
    if value is None:
        return default
    if isinstance(value, (int, float)):
        return float(value)
    value_str = str(value).strip()
    if value_str == "" or value_str.lower() in ("none", "nan", "null"):
        return default
    try:
        return float(value_str)
    except ValueError:
        return default


def _safe_int(value: Any, default: int = 0) -> int:
    """Convert value to int safely."""
    if value is None:
        return default
    if isinstance(value, int):
        return value
    try:
        return int(float(str(value).strip()))
    except (ValueError, TypeError):
        return default


def _safe_bool(value: Any) -> bool:
    """Convert common CSV/JSON truthy values to bool."""
    if isinstance(value, bool):
        return value
    if value is None:
        return False
    return str(value).strip().lower() in ("true", "1", "yes", "success", "succeeded")


def read_csv_dicts(path: Path) -> List[Dict[str, Any]]:
    """Read a CSV file as list of dictionaries."""
    if not path.exists():
        raise FileNotFoundError("Missing file: {}".format(path))
    with path.open("r", newline="") as f:
        reader = csv.DictReader(f)
        return [dict(row) for row in reader]


def read_json(path: Path) -> Any:
    """Read JSON if available."""
    if not path.exists():
        raise FileNotFoundError("Missing file: {}".format(path))
    with path.open("r") as f:
        return json.load(f)


def ensure_dir(path: Path) -> None:
    path.mkdir(parents=True, exist_ok=True)


