def find_episode_file(eval_dir: Path) -> Path:
    """Find the global episode result CSV."""
    candidates = [
        eval_dir / "episodes_all_models.csv",
        eval_dir / "episodes.csv",
    ]

    for candidate in candidates:
        if candidate.exists():
            return candidate

    # Fallback: collect model_xx/episodes.csv files later if no combined file exists.
    raise FileNotFoundError(
        "Could not find episodes_all_models.csv or episodes.csv in {}".format(eval_dir)
    )


def load_summary(eval_dir: Path) -> List[Dict[str, Any]]:
    """Load summary.csv if available; otherwise build summary from episodes."""
    summary_path = eval_dir / "summary.csv"
    if summary_path.exists():
        rows = read_csv_dicts(summary_path)
        return normalize_summary_rows(rows)

    # Fallback to JSON summary files inside model folders.
    summary_rows = []
    for model_dir in sorted(eval_dir.glob("model_*")):
        path = model_dir / "summary.json"
        if path.exists():
            row = read_json(path)
            if isinstance(row, dict):
                summary_rows.append(row)

    if summary_rows:
        return normalize_summary_rows(summary_rows)

    # Final fallback: build from episode CSV.
    episodes = load_episodes(eval_dir)
    return build_summary_from_episodes(episodes)


def load_episodes(eval_dir: Path) -> List[Dict[str, Any]]:
    """Load episode data from combined CSV or model subfolders."""
    combined = eval_dir / "episodes_all_models.csv"
    if combined.exists():
        return normalize_episode_rows(read_csv_dicts(combined))

    single = eval_dir / "episodes.csv"
    if single.exists():
        return normalize_episode_rows(read_csv_dicts(single))

    # Fallback: concatenate model_xx/episodes.csv files.
    all_rows = []
    for model_dir in sorted(eval_dir.glob("model_*")):
        ep_path = model_dir / "episodes.csv"
        if ep_path.exists():
            rows = read_csv_dicts(ep_path)
            for row in rows:
                if "model_id" not in row or row["model_id"] == "":
                    row["model_id"] = model_dir.name
                if "model_name" not in row or row["model_name"] == "":
                    row["model_name"] = model_dir.name
            all_rows.extend(rows)

    if not all_rows:
        raise FileNotFoundError(
            "Could not find episode CSV files in {}".format(eval_dir)
        )
    return normalize_episode_rows(all_rows)


def normalize_episode_rows(rows: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """Normalize common field types from episode CSV."""
    out = []
    for row in rows:
        new = dict(row)

        # Model identity
        model_name = str(new.get("model_name", new.get("model", new.get("model_id", "model"))))
        new["model_name"] = model_name
        new["model_id"] = str(new.get("model_id", model_name))
        new["algorithm"] = str(new.get("algorithm", ""))

        # Episode info
        new["episode"] = _safe_int(new.get("episode", new.get("ep", 0)))
        new["total_reward"] = _safe_float(new.get("total_reward", new.get("reward", float("nan"))))
        new["steps"] = _safe_int(new.get("steps", new.get("step_count", 0)))
        new["success"] = _safe_bool(new.get("success", new.get("done", False)))
        new["truncated"] = _safe_bool(new.get("truncated", False))

        # Optional final errors from info["error"] if generated by evaluator.
        for key in [
            "final_x_error",
            "final_y_error",
            "final_z_error",
            "final_xy_error",
            "final_yaw_error",
            "final_distance_error",
        ]:
            if key in new:
                new[key] = _safe_float(new.get(key))

        # Optional reward components.
        for key in [
            "reward_xy",
            "reward_z",
            "reward_yaw",
            "reward_visible",
            "docking_accuracy_reward",
            "smoothing_reward",
            "collision_reward",
            "collision_reward_sum",
        ]:
            if key in new:
                new[key] = _safe_float(new.get(key))

        out.append(new)
    return out


def normalize_summary_rows(rows: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """Normalize summary rows from CSV/JSON."""
    out = []
    numeric_keys = [
        "success_rate",
        "success_count",
        "timeout_count",
        "mean_reward",
        "std_reward",
        "median_reward",
        "mean_steps",
        "std_steps",
        "median_steps",
        "final_xy_error_mean",
        "final_z_error_mean",
        "final_yaw_error_mean",
        "mean_final_xy_error",
        "mean_final_z_error",
        "mean_final_yaw_error",
        "collision_reward_sum_mean",
        "collision_reward_sum_std",
        "collision_reward_sum_total",
        "mean_collision_reward",
        "std_collision_reward",
        "collision_reward_mean",
        "collision_reward_std",
        "mean_collision_reward_mean",
        "mean_collision_reward_std",
        "final_collision_reward_mean",
        "final_collision_reward_std",
    ]

    for row in rows:
        new = dict(row)
        model_name = str(new.get("model_name", new.get("model", new.get("model_id", "model"))))
        new["model_name"] = model_name
        new["model_id"] = str(new.get("model_id", model_name))
        new["algorithm"] = str(new.get("algorithm", ""))
        for key in numeric_keys:
            if key in new:
                new[key] = _safe_float(new[key])
        out.append(new)
    return out


def build_summary_from_episodes(episodes: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """Build model summary if summary.csv is not available."""
    grouped = group_by_model(episodes)
    summary = []
    for model_name, rows in grouped:
        rewards = np.array([_safe_float(r.get("total_reward")) for r in rows], dtype=float)
        steps = np.array([_safe_float(r.get("steps")) for r in rows], dtype=float)
        success = np.array([1.0 if _safe_bool(r.get("success")) else 0.0 for r in rows], dtype=float)

        collision_values = np.array([
            _safe_float(r.get("collision_reward_sum", r.get("mean_collision_reward", r.get("collision_reward"))))
            for r in rows
        ], dtype=float)

        summary.append({
            "model_name": model_name,
            "algorithm": str(rows[0].get("algorithm", "")) if rows else "",
            "num_episodes": len(rows),
            "success_rate": float(np.nanmean(success)) if len(success) else float("nan"),
            "success_count": int(np.nansum(success)) if len(success) else 0,
            "timeout_count": int(len(success) - np.nansum(success)) if len(success) else 0,
            "mean_reward": float(np.nanmean(rewards)) if len(rewards) else float("nan"),
            "std_reward": float(np.nanstd(rewards)) if len(rewards) else float("nan"),
            "median_reward": float(np.nanmedian(rewards)) if len(rewards) else float("nan"),
            "mean_steps": float(np.nanmean(steps)) if len(steps) else float("nan"),
            "std_steps": float(np.nanstd(steps)) if len(steps) else float("nan"),
            "median_steps": float(np.nanmedian(steps)) if len(steps) else float("nan"),
            "collision_reward_sum_mean": float(np.nanmean(collision_values)) if len(collision_values) else float("nan"),
            "collision_reward_sum_std": float(np.nanstd(collision_values)) if len(collision_values) else float("nan"),
            "collision_reward_sum_total": float(np.nansum(collision_values)) if len(collision_values) else float("nan"),
        })
    return summary


def group_by_model(rows: List[Dict[str, Any]]) -> List[Tuple[str, List[Dict[str, Any]]]]:
    """Return rows grouped by model_name, preserving sorted model order."""
    groups = {}
    for row in rows:
        model_name = str(row.get("model_name", row.get("model_id", "model")))
        if model_name not in groups:
            groups[model_name] = []
        groups[model_name].append(row)

    def sort_key(name: str) -> Tuple[int, str]:
        # Try to sort by model_id prefix if available, else by name.
        for row in groups[name]:
            model_id = str(row.get("model_id", ""))
            digits = "".join([c for c in model_id if c.isdigit()])
            if digits:
                try:
                    return (int(digits), name)
                except ValueError:
                    pass
        return (999999, name)

    return [(name, groups[name]) for name in sorted(groups.keys(), key=sort_key)]


